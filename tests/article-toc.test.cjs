const assert = require('node:assert/strict');
const fs = require('node:fs');
const Module = require('node:module');
const ts = require('typescript');
const filename = require('node:path').resolve('src/lib/article-toc.ts');
const source = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const compiled = new Module(filename, module);
compiled.filename = filename;
compiled.paths = Module._nodeModulePaths(require('node:path').dirname(filename));
compiled._compile(source, filename);
const { articleHtmlToc, headingId, headingIds } = compiled.exports;
const image = '<figure><img src="photo.jpg" alt="sample" width="700"><figcaption>Original</figcaption></figure>';
const input = '<h2 id="existing">First &amp; <strong>second</strong></h2>' + image + '<h3>Repeated</h3><h2>Repeated</h2><h2 id="existing">Again</h2><h2></h2>';
const result = articleHtmlToc(input);
assert.equal(result.headings.length, 4);
assert.equal(result.headings[0].id, 'existing');
assert.equal(result.headings[0].text, 'First & second');
assert.equal(result.headings[1].level, 3);
assert.equal(new Set(result.headings.map(h => h.id)).size, 4);
assert.equal(result.headings[2].id, `${headingId('Repeated')}-2`);
assert.ok(result.html.includes(image));
assert.equal(result.html.replace(/<h[23]\b[^>]*>/g, ''), input.replace(/<h[23]\b[^>]*>/g, ''));
assert.deepEqual(articleHtmlToc(input), result);
assert.deepEqual(articleHtmlToc('<p>Short article.</p>'), { html: '<p>Short article.</p>', headings: [] });
assert.equal(articleHtmlToc('<h3>Only heading</h3>').headings.length, 1);
assert.equal(articleHtmlToc('<!-- <h2>Comment</h2> --><script>"<h2>Script</h2>"</script><h2>Real</h2>').headings.length, 1);
assert.notEqual(articleHtmlToc('<div id="x"></div><h2 id="x">Heading</h2>').headings[0].id, 'x');
assert.equal(articleHtmlToc('<h2 id>Blank</h2>').html, `<h2 id="${headingId('Blank')}">Blank</h2>`);
assert.notEqual(articleHtmlToc('<h2 id="x"></h2><h2 id="x">Heading</h2>').headings[0].id, 'x');
assert.ok(articleHtmlToc('<h2 id-custom="kept">Heading</h2>').html.includes('id-custom="kept"'));
const reserve = headingId('Reserved');
assert.equal(articleHtmlToc(`<div id="${reserve}"></div><h2>Reserved</h2>`).headings[0].id, `${reserve}-2`);
const allocate = headingIds();
assert.equal(allocate('同じ見出し'), headingId('同じ見出し'));
assert.equal(allocate('同じ見出し'), `${headingId('同じ見出し')}-2`);
console.log('article-toc: 18 checks passed');
