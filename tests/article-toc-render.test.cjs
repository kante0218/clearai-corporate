const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const { renderToStaticMarkup } = require('react-dom/server');
const React = require('react');
const filename = path.resolve('src/components/ArticleToc.tsx');
const compiled = new Module(filename, module);
compiled.filename = filename;
compiled.paths = Module._nodeModulePaths(path.dirname(filename));
compiled._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2020 } }).outputText, filename);
const Toc = compiled.exports.default;
assert.equal(renderToStaticMarkup(React.createElement(Toc, { headings: [] })), '');
assert.equal(renderToStaticMarkup(React.createElement(Toc, { headings: [{id:'empty',text:' ',level:2}] })), '');
const html = renderToStaticMarkup(React.createElement(Toc, { headings: [{id:'real',text:'見出し',level:2}], collapsible: true }));
assert.match(html, /この記事の目次（1項目）/);
assert.match(html, /href="#real"/);
assert.doesNotMatch(html, /<details open/);
